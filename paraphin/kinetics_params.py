    ('K_CRYST', 1.0e-2),     # кристаллизация в объеме, [1/с], оценка
    ('K_DISS', 1.0e-1),      # растворение кристаллов, [1/с], оценка
    ('K_WALL', 1.0e-2),      # кристаллизация на стенках, [1/с], оценка
    # 2. Перенос частиц к стенке
    ('SHEAR_DISP', 0.5),     # коэффициент сдвиговой дисперсии, [-] (Leighton & Acrivos, 1987)
    ('GRAV_EFF', 0.25),      # доля стоксова оседания на стенку, [-] (геометрия изотропного пучка)
    ('DIFF_MULT', 1.0),      # множитель к броуновской диффузии частиц поверх constants.diff_mult, [-]
    ('D_CRYST', c.D),        # диаметр кристалла в ядре кинетики, [м]: по умолчанию D, подбор - без перекомпиляции
    # 3. Вынос отложений (Gruesbeck & Collins, 1982)
    ('ENT_RATE', 1.0e-4),    # скорость выноса, [1/с], оценка
    ('ENT_TAU', 1.0),        # критическое касательное напряжение, [Па], оценка
    # 4. Агрегация флокул (Смолуховский) и 5. «снежный ком» (Onaka & Sato, 2021)
    ('AGG_D0', 1.0e-7),      # диаметр первичной выпавшей частицы, [м]
    ('AGG_DF', 2.0),         # фрактальная размерность, [-]
    ('AGG_W', 1.0),          # коэффициент устойчивости Фукса (1 - каждое столкновение слипает), [-]
    ('SNOW_A', 10.0),        # рост захвата с осадком, [-], оценка
    # 6. Адсорбция асфальтенов и смол (кинетический Ленгмюр) и 7. смачиваемость (Qin et al., 2000)
    ('ADS_GMAX', 3.0e-6),    # предельная адсорбция, [кг/м^2] (3 мг/м^2; Dubey & Waxman, 1991)
    ('ADS_K', 200.0),        # константа Ленгмюра при ADS_T_REF, [1/доля масс.], оценка
    ('ADS_DH', -2.0e4),      # энтальпия адсорбции, [Дж/моль], оценка
    ('ADS_T_REF', 70.0),     # опорная температура, [C]
    ('ADS_RATE', 1.0e-4),    # скорость адсорбции при ADS_T_REF, [1/с], оценка
    ('ADS_RESIN', 0.5),      # отношение предельной адсорбции смол к асфальтенам, [-], оценка
    ('ADS_FILM', 0.0),       # форма кинетики: 0 - со стороны твердой фазы, 1 - пленочная
    ('OW_S_MIN', 0.10),      # нефтесмачиваемый набор ОФП: связанная вода, оценка
    ('OW_S_MAX', 0.80),      # то же: вода при остаточной нефти
    ('OW_N_O', 3.0),         # показатель ОФП нефти
    ('OW_N_W', 1.5),         # показатель ОФП воды
    # 8. Старение гель-отложения (Singh et al., 2000)
    ('AGE_C0', 0.1),         # доля парафина в свежем отложении, [-], оценка
    ('AGE_CMAX', 0.6),       # предельная доля парафина, [-]
    ('AGE_RATE', 1.0e-6),    # скорость старения, [1/с], оценка
    # 9-10. Глубинная фильтрация (Civan, 2015) и k(phi, sigma)
    ('FILT_KD', 2.0e-2),     # осаждение, [1/с]: Wang & Civan (2005) для Sutton & Roberts - 0.018-0.024
