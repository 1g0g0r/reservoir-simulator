"""Числовые параметры кинетики осаждения: значения по умолчанию и именованные индексы runtime-вектора `solver.kin`.

Флаги моделей (`wax_kinetics`, `entrainment`, ...) - константы `constants.py`, numba сворачивает по ним ветки при
компиляции. А числовые параметры тех же моделей живут в runtime-векторе `solver.kin`: ядра получают его аргументом.
Так калибровка по опытам (`experiments/`) меняет константы скоростей в уже скомпилированном процессе - без копии
пакета и 40 с компиляции на каждую оценку целевой функции. Значения ниже - единственный источник начальных значений;
обоснования - `docs/параметры_модели.md`, раздел «Кинетика осаждения». Новый параметр - строка в `_PARAMS`.

Поля кинетических моделей (`kx`) и их индексы - `paraphin/layout.py`.
"""
