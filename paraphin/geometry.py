"""Сетка радиусов пор и начальная функция пор по размерам: узлы, точные веса интегралов, производные константы.

Считается один раз при импорте; njit-ядра читают массивы как глобальные константы. `python -m paraphin.geometry` -
график fi_0.
"""
import warnings

import numpy as np

from paraphin.constants import (data_type, Nx, Ny, Nr, D, gamma, Lk, r_m, sigma_r, r_max, init_k, init_m,
                                D_asph, asphaltenes)

N = Nx * Ny  # размер матрицы давления

# Сетка радиусов равномерная. Сгущение у r_pass и r_max проверено и точности не дает: ошибка
# сидит там, где масса r^2*fi и r^4*fi (15-30 мкм), и сгущение к краям только отбирает оттуда узлы.
# Помогает лишь рост Nr. Схема при этом шага не предполагает - см. `dr_cv`. `r_max` - в constants.py:
# для керна с мелкими порами (Li et al., 2024) сетка масштабируется вместе с r_m.
r = np.linspace(0.0, r_max, Nr)
dr_cv = np.empty(Nr, data_type)  # ширина контрольного объема узла: знаменатель в `_update_fi`
dr_cv[1:-1] = (r[2:] - r[:-2]) * 0.5
dr_cv[0], dr_cv[-1] = (r[1] - r[0]) * 0.5, (r[-1] - r[-2]) * 0.5

# Начальная функция пор по размерам - логнормальная модель Косуги (Kosugi K. // Water Resour.
# Res. 1996. V. 32. No 9. P. 2697): r_m - медианный радиус, sigma_r - СКО ln r, мода в r_m*exp(-sigma_r^2).
# sigma_r = 0.4 и r_max/r_m = 3.3 - как у упаковок шаров (Ghanbarian, 2020,
# resources/литература/ghanbarian2020.pdf, табл. 1); на r_max плотность 0.3% максимума, ниже
# r_pass лежит ~1% капилляров. Нормировка на единичный интеграл: sum(fi_0*dr_cv) = 1.
fi_0 = np.zeros(Nr, data_type)
fi_0[1:] = np.exp(-0.5 * (np.log(r[1:] / r_m) / sigma_r) ** 2) / (np.sqrt(2 * np.pi) * sigma_r * r[1:])
fi_0 /= (fi_0 * dr_cv).sum()

# Коэффициент извилистости: при нем пучок капилляров с fi_0 имеет ровно проницаемость пласта,
# k_0 = m_0*<r^4>/(8*eta^2*<r^2>), а средняя скорость в капилляре um = |grad p|*r^2/(8*eta*mu) (`calc_Um_r2`)
# согласована с дарсиевской. При eta = 1 и r_m = 12 мкм пучок давал k в ~70 раз больше k_0 = 200 мД,
# и во столько же была завышена um, а с ней скорости блокирования и сужения.
eta = float(np.sqrt(init_m * (r ** 4 * fi_0 * dr_cv).sum() / (8.0 * init_k * (r ** 2 * fi_0 * dr_cv).sum())))

# массивы радиусов пор в необходимых степенях
r1 = r
r2 = r * r
r3 = r2 * r
r4 = r3 * r
r5 = r4 * r
r6 = r5 * r
cbrt_r1 = np.cbrt(r1)

# r < r_pass - частица не проходит горло и блокирует капилляр (Ub), r >= r_pass - оседает на
# стенке и сужает его (Ur < 0). Сужение схема учитывает переносом fi по оси радиусов.
r_pass = D * 0.5 / gamma
n_pass = int(np.searchsorted(r1, r_pass, side='left'))  # первый узел с r >= r_pass

# Узловые веса объема каналов: при кусочно-линейной fi интеграл r^2*fi (пористость, `_calculate_integrals`)
# равен sum(w2_cv*fi) точно, w2_cv[ij] - интеграл r^2 по «шапочке» узла ij. В тех же единицах `calc_qp_m_k_fi`
# считает, какой объем каналов за шаг ушел из fi в блокированные.
_a, _b = r[:-1], r[1:]
w2_cv = np.zeros(Nr, data_type)
w2_cv[1:] += ((_b ** 4 - _a ** 4) / 4 - _a * (_b ** 3 - _a ** 3) / 3) / (_b - _a)  # восходящая половина
w2_cv[:-1] += (_b * (_b ** 3 - _a ** 3) / 3 - (_b ** 4 - _a ** 4) / 4) / (_b - _a)  # нисходящая половина
# Те же веса для r^1: sum(w1_cv*fi) = int r*fi dr точно. Удельная поверхность пучка fi_0 - поверхность породы,
# на которой адсорбируются асфальтены и смолы (`Deposition._adsorption`): емкость Ленгмюра - свойство породы,
# ее измеряют на единицу массы породы, и заткнутый позже канал адсорбированное не отдает.
w1_cv = np.zeros(Nr, data_type)
w1_cv[1:] += ((_b ** 3 - _a ** 3) / 3 - _a * (_b ** 2 - _a ** 2) / 2) / (_b - _a)
w1_cv[:-1] += (_b * (_b ** 2 - _a ** 2) / 2 - (_b ** 3 - _a ** 3) / 3) / (_b - _a)
surf_0 = float(2.0 * init_m * (w1_cv * fi_0).sum() / (w2_cv * fi_0).sum())  # [1/м]
# Пробка: канал затыкает один кристалл размера D, его объем pi*D^3/6 против объема канала pi*r^2*Lk, то есть в
# единицах r^2 - D^3/(6*Lk) на канал (для D = 15 мкм, Lk = 0.3 мм и r = 10 мкм это 2% канала). Больше объема
# самого канала пробка не бывает. Число каналов у узла - fi*dr_cv, отсюда вес D^3/(6*Lk)*dr_cv.
plug_cv = np.minimum(D ** 3 / (6.0 * Lk) * dr_cv, w2_cv)

# Те же точные веса «шапочек» для r^4 (проводимость пучка: множитель подвижности геля `equations/Gel.py`) и для
# r^(4/3) (оценка потери пор при сужении флокулами асфальтенов, u_a ~ r^(1/3), `calc_qp_m_k_fi_2`).
w4_cv = np.zeros(Nr, data_type)
w4_cv[1:] += ((_b ** 6 - _a ** 6) / 6 - _a * (_b ** 5 - _a ** 5) / 5) / (_b - _a)
w4_cv[:-1] += (_b * (_b ** 5 - _a ** 5) / 5 - (_b ** 6 - _a ** 6) / 6) / (_b - _a)
w43_cv = np.zeros(Nr, data_type)
w43_cv[1:] += (0.3 * (_b ** (10 / 3) - _a ** (10 / 3)) - 3 / 7 * _a * (_b ** (7 / 3) - _a ** (7 / 3))) / (_b - _a)
w43_cv[:-1] += (3 / 7 * _b * (_b ** (7 / 3) - _a ** (7 / 3)) - 0.3 * (_b ** (10 / 3) - _a ** (10 / 3))) / (_b - _a)

# Флокула асфальтенов проходит горло шире r_pass_a и оседает на стенках (сужение), уже - затыкала бы горло.
# При D_asph = 1 мкм r_pass_a = 1.25 мкм меньше первого ненулевого узла сетки радиусов: блокирования
# флокулами на этой сетке нет, работает только сужение (см. `calc_qp_m_k_fi_2`).
r_pass_a = D_asph * 0.5 / gamma
n_pass_a = int(np.searchsorted(r1, r_pass_a, side='left'))
if asphaltenes and n_pass_a > 1:
    warnings.warn(f'Флокулы асфальтенов D_asph = {D_asph} м закупоривали бы капилляры r < {r_pass_a:.2e} м '
                  f'({n_pass_a} узлов сетки радиусов), но блокирование флокулами не моделируется - только сужение')


if __name__ == '__main__':
    import plotly.graph_objects as go

    fig = go.Figure()
    fig.add_trace(go.Scatter(x=r, y=fi_0, mode='lines'))
    fig.show()
