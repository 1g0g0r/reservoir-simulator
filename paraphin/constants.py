from pathlib import Path
import numpy as np

data_type = np.float64
CONTOUR_PLOT = False
LOGGING = False  # Всегда - False. Логирование нужно только в редких случаях при отладке

# Перевод единиц измерения
day_to_sec = 86400.0
bar_to_pa = 1e5
darcy_to_m2 = 9.869233e-13
cpoise_to_Pas = 1e-3
kal_to_J = 4.1868

# Параметры сетки
Nr = 31          # Число узлов сетки радиусов капилляров
Nx, Ny = 75, 75  # Число узлов сетки по x и y
X_min, X_max = 0., 200.  # Длина пласта, [м]
Y_min, Y_max = 0., 200.  # Ширина пласта, [м]
h = 10.0  # Толщина пласта, [м]
hx = (X_max - X_min) / Nx
hy = (Y_max - Y_min) / Ny
area = hx * hy
volume = area * h

# Параметры времени задачи
Time_end = day_to_sec * 365 * 9.0  # Время моделирования
dt = day_to_sec / 2e1     # Шаг дискретизации по времени
max_eta = 0.98            # Предельная обводненность
sol_time_step = dt * 50  # шаг по времени для сохранения результатов и записи в лог

# Параметры скважин
rw = 0.1              # Радиус скважин, [м]
Pw = 150 * bar_to_pa  # Давление на нагнетательной скважине, [Па]
Po = 50 * bar_to_pa   # Давление на добывающей скважине, [Па]
Twater = 20.0         # Температура нагнетаемой воды, [С]

# Параметры ОФП
S_min = 0.18
S_max = 0.70
n_power = 2

# Учет перетоков тепла через кровлю и подошву пласта
heat_losses: int = 2

# Данные инициализации
init_p   = (Pw + Po) / 2  # [Па]
init_S   = S_min
# Массовая доля парафина: нефть Жетыбая - 24.93% (Li et al., Processes 2024, 12:421), по ней же подобрана
# растворимость (см. Tm, alpha ниже); Узень, XIII горизонт - 22-29% масс. (Togasheva et al., Eng 2026, 7:184).
init_Wp  = 0.25
init_Wps = 0.0
init_k   = 0.2 * darcy_to_m2  # [м^2]
init_m   = 0.3
init_T   = 70  # [C]
init_qp  = 0.0
init_h_sloy = 0.0
porous_volume = (X_max - X_min) * (Y_max - Y_min) * h * init_m
geological_reserves = porous_volume * (1.0 - init_S)  # Геологические запасы пласта
_re = 0.14 * np.sqrt(hx * hx + hy * hy)               # Радиус контура питания скважины, [м]

# Параметры флюидов
ro_w  = 1000.0  # Плотность воды, [кг/м^3]
ro_o  = 860.0   # Плотность нефти, [кг/м^3]
ro_p  = 900.0   # Плотность кристаллизованного парафина, [кг/м^3]
ro_f  = 2700.0  # Плотность пласта, [кг/м^3]
ro_ff = 2400.0  # Плотность окружающих пласт пород, [кг/м^3]
c_w  = 4200 # Теплоемкость воды, [Дж/(кг·C)]
c_o  = 2000 # Теплоемкость нефти, [Дж/(кг·C)]
c_p  = 2200 # Теплоемкость парафина, [Дж/(кг·C)]
c_f  = 1000 # Теплоемкость пласта, [Дж/(кг·C)]
c_ff = 1000 # Теплоемкость окружающих пласт пород, [Дж/(кг·C)]
K_p  = 0.2  # Теплопроводность парафина, [Вт/(м·С)]
K_w  = 0.6  # Теплопроводность воды, [Вт/(м·С)]
K_o  = 0.12 # Теплопроводность нефти, [Вт/(м·С)]
K_f  = 1.8  # Теплопроводность пласта, [Вт/(м·С)]
K_ff = 2.0  # Теплопроводность окружающих пород пласта, [Вт/(м∙C)]

# Параметры моделирования кольматации\суффозии
suffusion = False  # Учет суффозии (вынос осевших частиц потоком)
g     = 9.81   # Ускорение свободного падения, [м/с^2]
# Диаметр частиц: кристаллы ~1 мкм при WAT вырастают до ~10 мкм (Hammami et al., 1997, resources/литература/
# парафиновое/hammami1997.pdf); в керне закупориваются горла 20-70 мкм (Sandyga et al., JPEPT 2020, там же).
# Вместе с gamma задает r_pass = D/(2*gamma). D и Lk откалиброваны по керновому опыту 1 Sutton & Roberts (1974)
# (`python твт_статья/core_flood.py`): СКО k/k0 0.058 на сетке 5 x 4 (d_p 10-20 мкм, L_k 30-1000 мкм); Lk ~ размер
# зерна песчаника. D задает начальный провал k (блокирование каналов r <= D/(2*gamma)), Lk - длину зоны осаждения.
D     = 15e-6  # Размер частицы, [м]
betta = 0.01   # Доля блокируемых каналов, [-]
gamma = 0.4    # Отношение радиуса горла к радиусу канала, [-]
Lk    = 3e-4   # Средняя длина капилляра, [м]
r_m     = 12e-6  # Медианный радиус капилляров в модели Косуги (Kosugi, 1996), [м]
sigma_r = 0.4    # Стандартное отклонение ln r в модели Косуги, [-]
r_max   = 40e-6  # Наибольший радиус сетки радиусов, [м]; r_max/r_m = 3.3, см. `paraphin/__init__.py`
Cf    = 3e-2   # Коэффициент сопротивления частицы в нефти, [-]
Delta = 0.005  # Кинетическая константа суффозии, [1/м]
R     = 8.31446261815324  # Газовая постоянная, [J/K/mol]
k_B   = 1.380649e-23      # Постоянная Больцмана, [Дж/К]: броуновская диффузия частиц по Стоксу-Эйнштейну, см. `u_r`
# Множитель к коэффициенту диффузии по Стоксу-Эйнштейну - ручка калибровки (`твт_статья/pore_distribution.py`).
# В сужение D_p входит только как D_p^2/Lk, поэтому множитель f равносилен Lk/f^2 (кроме объема пробки D^3/(6*Lk)).
diff_mult = 1.0
min_Wps_bound = 1e-6  # Концентрация частиц, начиная с которой начинается расчет кольматации и суффозии

# Параметры вязкости нефти (уравнение Аррениуса, см. `math_utils/fluids_correlations.py`).
# Задается опорной точкой, а не предэкспонентой: менять энергию активации при фиксированном
# предэкспоненциальном множителе означало бы заодно менять вязкость на порядки.
E_activation = 25000.0  # Энергия активации вязкого течения нефти, [Дж/моль]  # TODO уточнить по замерам
mu_o_ref = 5.769e-3     # Вязкость нефти в опорной точке, [Па*с]
T_mu_ref = 70.0         # Опорная температура для вязкости нефти, [C]

# Параметры парафина
phi_max = 0.6  # Предельная объемная доля кристаллов парафина в нефти (плотная упаковка), [-]
MW = 410.0  # Молекулярная масса парафина, [г/моль]
M_o = 250.0 # Молярная масса нефтяного псевдокомпонента, [г/моль]
# Растворимость (6.1): один псевдокомпонент парафина в идеальном растворе. Tm и alpha в ней - эффективные
# параметры кривой выпадения, а не свойства чистого вещества: подобраны МНК по кривой выпадения нефти Жетыбая
# (Li et al., 2024, рис. 3б; 24.93% парафина) в интервале 10-45 C, `python твт_статья/core_flood.py --fit`,
# отклонение не больше 1.5%. Корреляции Вона при MW = 410 давали ту же точку помутнения (43.7 C против 45.7 C по ДСК),
# но при 35 C выпадало 15.7% вместо 5%: кривая многокомпонентного парафина положе, чем у одного н-алкана.
Tm = 82.8                # Эффективная температура плавления в (6.1), [C]
Tm_K = Tm + 273.15       # Она же в кельвинах: в (6.1) температуры абсолютные
alpha = 37.4e3           # Эффективная теплота в (6.1), [Дж/моль]
# Теплота кристаллизации в уравнении энергии - калориметрическая, а не эффективная alpha: корреляция Вона
# (Won, 1986) при MW = 410 дает 82.3 кДж/моль = 201 Дж/г - как измеренные 81.7 кДж/моль у Sandyga et al. (2020)
# и 210 Дж/г, принятые Li et al. (2024) для пересчета ДСК. На единицу массы MW сокращается.
latent_heat = 0.1426 * (374.5 + 0.02617 * MW - 2.0172e4 / MW) * kal_to_J * 1e3  # [Дж/кг]

# Параметры адаптивного шага по времени.
CFL_target = 1.0        # целевое число Куранта для явной схемы по насыщенности
dt_growth  = 1.2        # максимальный рост шага за одну итерацию
dt_max     = dt         # шаг не растет выше стартового
dt_min     = dt * 1e-3  # нижняя граница шага, [с]

# Параметры решателя уравнения давления (ленточный Холецкий, см. utils/math_utils/band_solver.py).
# Матрица меняется на ~0.2% за шаг, поэтому фактор пересобирается не каждый шаг, а промежуточные добираются PCG
# с ним в роли предобуславливателя. Значение 1 отключает PCG совсем. Оптимальный период растет с сеткой:
# факторизация стоит ~Nx^3*Ny, а итерация PCG (та же подстановка с фактором) ~Nx^2*Ny, то есть их отношение линейно по Nx.
# Замерами на 50x50 оптимум пологий между 12 и 40, взято 20 - отсюда коэффициент 20/50 = 0.4.
# Снизу 5 (мелкая сетка, факторизация дешевая), сверху 40: дальше матрица за период уходит слишком далеко
# и PCG перестает укладываться в p_pcg_maxit, а точный путь съедает выигрыш.
p_refactor_period = min(40, max(5, Nx * 2 // 5))  # через сколько шагов пересобирать фактор Холецкого
p_pcg_rtol        = 1e-10  # относительная невязка PCG на промежуточных шагах
p_pcg_maxit       = 20     # не уложился - фактор пересобирается и система решается точно

