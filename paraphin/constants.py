gel_mobility_min = 0.05     # нижняя граница множителя подвижности: матрица давления остается положительно определенной
# Вязкость от давления (Barus): mu *= exp(alpha_p_visc*(P - P_ref_wax)). Множитель ложится на вязкость
# дегазированной нефти (Li 2024); снижение вязкости растворенным газом не учтено, поэтому с флагом
# pressure_viscosity вязкость живой нефти - оценка сверху (в демо +20% при 12 МПа, -2.3 п.п. КИН).
