"""Пакет содержит реализацию решения сеточных уравнений.

Соглашения по аргументам
------------------------
Функции уравнений вызываются из `Solver._equations_loop` по одной ячейке и получают поля плоскими
numpy-массивами позиционно (jitclass не потянет весь набор полей, см. CLAUDE.md). Поля описаны здесь
один раз, чтобы не повторять один и тот же блок в каждой функции; в докстрингах самих функций
остается только то, что специфично для уравнения.

`i, j` - индексы текущей ячейки; `dt` - текущий шаг по времени, [с]; `t` - физическое время с начала
расчета, [с].

Каждое динамическое поле живет тремя массивами: `X` (текущий слой), `X_0` (предыдущий),
`new_X` (новый). Функция читает текущий слой и пишет в `new_*`; `_swap_time_steps` их сдвигает.

Поля (Nx, Ny), если не указано иное:
    p           давление, [Па]
    S           водонасыщенность, [-]
    T           температура, [C]
    m           пористость, [-]
    k           проницаемость, [м^2]
    mu_o, mu_w  вязкости нефти и воды, [Па*с]
    lam_o, lam_w    подвижности фаз k*pf/mu, посчитанные `calc_mobility` один раз за шаг,
                    [м^2/(Па*с)]
    C_o, C_w, C_p, C_f          теплоемкости нефти, воды, парафина и пласта,
                                [Дж/(кг*C)]
    Wo          массовая доля масляного компонента в нефти, [-]
    Wp          массовая доля растворенного парафина в нефти, [-]
    Wps         массовая доля взвешенных частиц парафина в нефти, [-]
    Wps_dep     массовая доля осевшего на порах парафина, [-]
    qp          скорость отложения парафина в общем объеме породы, [1/с]
    E_ff        накопленный интеграл перегрева кровли и подошвы по глубине, [C*м];
                состояние метода Винсома-Вестервельда, см. `equations/Temperature.py`
    grad_p      модуль градиента давления в центре ячейки, [Па/м]
    Um_r2       средняя скорость в капилляре без множителя r^2, [1/(м*с)]
    cells_S_eq, cells_Wp_eq, cells_T_eq     суммарные перетоки воды, нефти и тепла через грани
                                            ячейки, заполняет `flows_in_cells`
    cells_Q_out суммарный исходящий объемный поток через грани, [м^3/с]; нужен для оценки CFL

Поля (Nx, Ny, Nr) - распределения по радиусам пор (сетка радиусов `r1` в `paraphin/__init__.py`):
    fi          функция распределения пор по размерам, [-]
    h_sloy      толщина осадочного слоя парафина, [м]
    Ur          скорость изменения радиуса капилляра, [м/с]
    Ub          скорость блокирования капилляров, [1/с]

Прочее:
    boundary_conditions     (4, 3, 2): граница -> поле -> (тип, значение), индексы из enum'ов
                            `Bound` / `DataField` / `TypeBC`
    well                    объект `WellStruct` (jitclass), см. `utils/well.py`

Порядок вызовов внутри `_equations_loop` значим: `wps_wp_equation` читает `cells_Wp_eq` до того,
как `flows_in_cells` перезапишет буфер, то есть работает с перетоками предыдущего шага, а
`saturation_equation` и `temperature_equation` - с текущими.
"""
