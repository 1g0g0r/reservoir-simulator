"""Пакет содержит реализацию решения сеточных уравнений.

Соглашения по аргументам
------------------------
Функции уравнений вызываются из `Solver._equations_loop` по одной ячейке и получают поля плоскими
numpy-массивами позиционно (jitclass не потянет весь набор полей, см. CLAUDE.md). Поля описаны здесь
один раз, чтобы не повторять один и тот же блок в каждой функции; в докстрингах самих функций
остается только то, что специфично для уравнения.

`i, j` - индексы текущей ячейки; `dt` - текущий шаг по времени, [с]; `t` - физическое время с начала
расчета, [с].

Каждое динамическое поле живет двумя массивами: `X` (текущий слой) и `new_X` (новый); предыдущий слой
`T_0` есть только у температуры. Функция читает текущий слой и пишет в `new_*`; `_swap_time_steps` их сдвигает.

Поля (Nx, Ny), если не указано иное:
    p           давление, [Па]
    S           водонасыщенность, [-]
    T           температура, [C]
    m           пористость, [-]
    k           проницаемость, [м^2]
    mu_o, mu_w  вязкости нефти и воды, [Па*с]
    lam_o, lam_w    подвижности фаз k*pf/mu, посчитанные `calc_mobility` один раз за шаг,
                    [м^2/(Па*с)]
    lam_h           эффективная теплопроводность ячейки, там же, [Вт/(м*C)]
    C_o, C_w, C_p, C_f          теплоемкости нефти, воды, парафина и пласта,
                                [Дж/(кг*C)]
    Wo          массовая доля нефтяного компонента (все, кроме парафина) - не хранится, 1 - Wp - Wps
    Wp          массовая доля растворенного парафина в нефтяной фазе, [-]
    Wps         массовая доля взвешенных частиц парафина в нефтяной фазе, [-]
                Доли массовые, а не объемные: замыкающее соотношение w_o + w_p + w_ps = 1
                выполняется по массе (масса любого компонента фазы - m*S_o*ro_o*w_k, одна и та же
                плотность фазы ro_o для всех трех). ro_p - плотность кристаллизованного парафина,
                используется только для кристаллов в порах: сток q_p1 + q_p2 в балансах групп
                парафина (`equations/Components.py`) и теплоемкость (m_0-m)*ro_p*C_p в уравнении
                энергии (`equations/Temperature.py`). Wp и Wps - суммы по группам парафина.
    m           включает тупиковый объем блокированных каналов: проводящие каналы описывает `fi`,
                блокированные уходят из нее, но их объем с нефтью остается пористостью
    qp1         скорость потери порового объема на осаждение парафина на стенках пор, [1/с]
    qp2         скорость потери порового объема на пробки в горлах блокированных каналов, [1/с]
                (один кристалл на канал); q_p1 + q_p2 = -dm/dt по построению
    E_ff        накопленный интеграл перегрева кровли и подошвы по глубине, [C*м];
                состояние метода Винсома-Вестервельда, см. `equations/Temperature.py`
    grad_p      модуль градиента давления в центре ячейки, [Па/м]
    Um_r2       средняя скорость в капилляре без множителя r^2, [1/(м*с)]
    cells_S_eq, cells_T_eq      суммарные перетоки воды и тепла через грани ячейки, заполняет
                                `flows_in_cells`; туда же `_wells_loop` добавляет дебиты скважин,
                                поэтому уравнения делят их на поля нового слоя
    src_S, src_T, src_Qo        источники скважин в тех же единицах (src_Qo - дебит нефти, [м^3/с]),
                                заполняет `_wells_loop` до цикла по ячейкам
    cells_Q_out суммарный объемный отток через грани, [м^3/с]; его читает еще `_calc_dt` для
                ячеек со скважинами
    cells_Qo_out, cells_T_out   отток нефти через грани и тепловой отток ячейки из `flows_in_cells`
    cells_W_eq, Fo              приток единственного переносимого компонента (NC_T = 1) или потоки нефтяной
                                фазы через четыре грани (Nx, Ny, 4) - по ним `components_equation` переносит компоненты

Поля (Nx, Ny, Nr) - распределения по радиусам пор (сетка радиусов `r1` в `paraphin/geometry.py`):
    fi          функция распределения пор по размерам, [-]
    h_sloy      толщина осадочного слоя парафина, [м]
    Ur          скорость изменения радиуса капилляра, [м/с]
    Ub          коэффициент блокирования капилляров b(r), [1/с]; сама скорость ub = b(r)*fi,
                разделение нужно, чтобы взять слагаемое блокирования неявно в `Pore_bundle.update_fi_rows`

Состав нефти (`wax_characterization`: 'single' - один псевдокомпонент парафина, 'scn'/'gamma' - группы; флаги
`asphaltenes`, `gelation`; см. `paraphin/oil_composition.py`, `docs/физическая_модель.md`; индексы - `paraphin/layout.py`):
    Wc          (Nx, Ny, NC) доли компонентов: [:N_W] группы парафина (растворенные + взвешенные),
                IA_D растворенные асфальтены, IA_F флокулы, I_R смолы, [-]; переносятся первые NC_T
    Ws          (Nx, Ny, N_W) взвешенные кристаллы по группам, [-]; `new_Ws[i, j]` - буфер `sle_split`
    Hl          носитель скрытой теплоты sum_k (L_k/latent_heat)*w_k^dis, [-]; при одной группе - сам Wp
    Dep         (Nx, Ny, NC) накопленные отложения по компонентам, [кг/м^3 породы]
    bc_Wc       (4, NC) состав нефти, втекающей через границу с ГУ Дирихле `DataField.Paraffin`
    src_Qo      дебит нефти скважины, [м^3/с]
    kx          (Nx, Ny) структурный dtype `layout.KX` - поля механизмов: в ядре `kx[i, j].ua`, в том числе
                ua - коэффициент сужения капилляров флокулами, u_a = Ua*r^(1/3), [м^(2/3)/с], и
                qpa - скорость потери порового объема на осадок асфальтены + смолы, [1/с]
                (q_p1 + q_p2 + q_pa = -dm/dt)
    rows        (Nx) dtype `layout.ROWS` скретч: рабочие профили ячейки (`rows[i].u`, ...), свои на каждый i
    mu_p        вязкость нефти без геля (пластическая), [Па*с]; без флага `gelation` - сам mu_o
    Phi         множитель подвижности нефти от геля (Букингем-Райнер в пучке капилляров), [-]

Прочее:
    boundary_conditions     (4, 4, 2): граница -> поле -> (тип, значение), индексы из enum'ов
                            `Bound` / `DataField` / `TypeBC`
    wells, w                массив скважин (строки с именованными столбцами) и номер скважины, см. `utils/well.py`

Порядок вызовов внутри `_equations_loop` значим и повторяет порядок вычислений на шаге из
постановки задачи: перетоки через грани (они читают только текущий слой, а ограничителю осаждения нужен отток),
кольматация (fi -> m, k, q_p1, q_p2), дебиты скважин, насыщенность, перенос компонентов (он делит на (m*S_o)
нового слоя) и последней температура (ей нужен w_p нового слоя для скрытой теплоты кристаллизации).
"""
