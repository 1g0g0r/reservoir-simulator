"""Баланс парафина: перенос суммарной доли и разделение на растворенный и взвешенный."""
import numpy as np
from numba import njit

from paraphin.constants import data_type, ro_o, ro_p, volume, Tm, Tm_K, R, alpha, MW, M_o

alpha_R = alpha / R
_RO_P_RO_O = ro_p / ro_o  # множитель у стока q_p1 в (3), поделенном на ro_o, а не на ro_p


@njit(cache=True)
def wp_equation(i, j, qp1, qp2, m, S, Wp, Wps, T, cells_Wp_eq, new_m, new_S, new_Wp, new_Wps, dt, _paraphin) -> None:
    """Перенос парафина и его разделение на растворенный и взвешенный.

    Обе формы парафина переносятся нефтяной фазой с одной и той же скоростью, поэтому решается
    одно уравнение сохранения - для суммарной массовой доли w = w_p + w_ps (это и есть исходное
    уравнение баланса парафина, поделенное на плотность нефтяной фазы ro_o - той же, на которую
    делится и баланс нефтяного компонента (2), так как обе доли массовые):

        (m*S_o*w)^new = (m*S_o*w) + dt*cells_Wp_eq/|V| - dt*(ro_p/ro_o*q_p1 + w*q_p2)

    `q_p1` - осаждение на стенках пор: изымается чистый парафин с плотностью ro_p, а уравнение
    поделено на ro_o, отсюда множитель ro_p/ro_o (`_RO_P_RO_O`). `q_p2` - блокирование каналов:
    из фильтрации выводится весь объем канала вместе с нефтью той же плотности ro_o, поэтому
    парафин уходит в своей доле `w` без множителя плотностей. Разделять их обязательно - одной
    величиной dm/dt обойтись можно только в уравнении фазы, где стоит их сумма.

    Разделение на растворенный и взвешенный - алгебраическое, по условию фазового равновесия
    (см. `_wp_saturated`). Отдельная переменная для скорости кристаллизации не нужна: в сумме
    w_p + w_ps она сокращается. Такая запись автоматически дает w_p, w_ps >= 0 и замыкающее
    соотношение w_o + w_p + w_ps = 1.

    Температура берется с текущего слоя, а не с нового: уравнение энергии считается после, а его
    слагаемое скрытой теплоты должно быть согласовано с тем самым w_p, который в итоге сохраняется.

    Описание аргументов - в докстринге пакета `paraphin.equations`.
    """
    if _paraphin:
        w_sum = Wp[i, j] + Wps[i, j]
        mSo_new = new_m[i, j] * (1.0 - new_S[i, j])

        if mSo_new <= 1e-12:  # ячейка промыта водой: нефтяной фазы нет, переносить нечего
            new_Wp[i, j] = 0.0
            new_Wps[i, j] = 0.0
            return None

        w_new = (m[i, j] * (1.0 - S[i, j]) * w_sum
                 + dt * (cells_Wp_eq[i, j] / volume - _RO_P_RO_O * qp1[i, j]
                         - w_sum * qp2[i, j])) / mSo_new
        w_new = min(max(w_new, 0.0), 1.0)

        new_Wp[i, j] = _wp_saturated(w_new, T[i, j])
        new_Wps[i, j] = w_new - new_Wp[i, j]


@njit(cache=True)
def _wp_saturated(w_sum: data_type, T: data_type) -> data_type:
    """Равновесная массовая доля растворенного парафина в нефтяной фазе, [-].

    Выпадающий парафин образует чистую твердую фазу, поэтому коэффициент распределения модели
    Вона задает не пропорцию между растворенным и взвешенным парафином, а предел растворимости -
    мольную долю парафина в насыщенном растворе:

        x_sat(T) = min(1, exp[-(alpha/R)*(1/T - 1/T_m)]),   T, T_m в К.

    Температуры именно абсолютные, и знак экспоненты отрицательный: при T < T_m раствор
    насыщается раньше. Прежняя запись Wps = Wp*exp[+(alpha/R)*(1/T - 1/T_m)] давала выпадение
    парафина и выше температуры плавления, а пропорциональность Wps ~ Wp физического смысла не
    имеет.

    Мольная доля переводится в массовую (в балансах доли массовые, а не мольные) через молярные
    массы напрямую - плотности здесь не нужны, так как оба компонента (парафин и нефтяной)
    относятся к одной и той же массе нефтяной фазы; взвешенные частицы в раствор не входят,
    поэтому предел относится к сумме w_o + w_p = 1 - w_ps:

        w_hat = x_sat*M_w / (x_sat*M_w + (1 - x_sat)*M_o)
        w_p_sat = w_hat/(1 - w_hat) * w_o,   w_o = 1 - w_sum.

    Избыток растворенного парафина над w_p_sat переходит во взвешенное состояние, при
    недосыщении взвешенные частицы растворяются.
    """
    if T >= Tm:
        return w_sum  # выше температуры плавления парафин растворим полностью

    x_sat = np.exp(-alpha_R * (1.0 / (T + 273.15) - 1.0 / Tm_K))
    if x_sat >= 1.0:
        return w_sum

    w_hat = x_sat * MW / (x_sat * MW + (1.0 - x_sat) * M_o)

    return min(w_sum, w_hat / (1.0 - w_hat) * (1.0 - w_sum))
