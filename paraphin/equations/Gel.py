"""Гелеобразование парафинистой нефти: предел текучести и течение Букингема-Райнера в пучке капилляров.

Ниже точки гелеобразования кристаллы парафина сцепляются в пространственную сетку, и нефть становится
вязкопластичной: течет, только если касательное напряжение превысило предел текучести tau_y. Гель
возникает уже при нескольких процентах выпавшего парафина (около 2 % масс.: Letoffe et al., Fuel 1995,
74:810; Venkatesan et al., CES 2005, 60:3587), а tau_y растет с долей кристаллов степенным образом, как у
фрактальных гелей (Shih et al., Phys. Rev. A 1990, 42:4772; Visintin et al., Langmuir 2005, 21:6240):

    tau_y = mult*tau_ref*((phi_s - phi_gel)/(phi_ref - phi_gel))^n,   phi_s > phi_gel.       (1)

В объеме (реометр) phi_s - доля взвешенных кристаллов. В поре кристаллы, выпавшие из протекающей нефти,
почти сразу оседают на стенках (осаждение лимитируется подводом, `calc_qp_m_k_fi`), и взвеси остается
доли процента - но осадок на стенках и есть гель парафин-нефть с захваченной нефтью (Singh et al.,
AIChE J 2000, 46:1059). Поэтому в поре сетку образуют и осадок, и взвесь, и доля твердой фазы геля

    phi_s = (m*S_o*phi_взвесь + V_осадок)/(m*S_o + V_осадок),                                 (1а)

V_осадок = m0 - m за вычетом осадка асфальтенов - объем парафина в порах на единицу объема породы
(`pore_solid_fraction`). Сужение каналов осадком (fi) описывает, где лежит твердая фаза, предел текучести -
может ли оставшаяся в поре нефть сдвинуть ее сетку.

В капилляре радиуса r с градиентом давления вдоль него G напряжение на стенке tau_w = r*G/2; в пучке
G = |grad p|/eta (та же извилистость, что согласует пучок с k_0, `paraphin/__init__.py`). Расход
бингамовской жидкости отличается от пуазейлевского множителем Букингема-Райнера (Buckingham, 1921):

    F(xi) = 1 - 4*xi/3 + xi^4/3 при xi = tau_y/tau_w < 1, иначе 0,                           (2)

а проницаемость пучка пропорциональна интегралу r^4*fi (Wu, Pruess & Witherspoon, SPE RE 1992, 7:369;
Chevalier et al., JNNFM 2013, 195:57 - «начальный градиент» как следствие распределения пор). Поэтому
множитель подвижности нефти

    Phi = int r^4*fi*F dr / int r^4*fi dr                                                     (3)

плавно падает от 1 до 0: сначала перестают течь узкие капилляры, потом широкие. Phi зависит от
градиента давления, поэтому берется с прошлого шага (матрица давления остается симметричной) и
релаксирует к (3) с временем `gel_time` - это и тиксотропия (Dimitriou & McKinley, Soft Matter 2014),
и демпфер: без него запаздывание по градиенту дает колебания «застыл - сорвался».
"""
from numba import njit

from paraphin import r1, w4_cv, eta
from paraphin.constants import Nr, gel_phi, gel_tau_ref, gel_phi_ref, gel_n, gel_tau_mult

_TAU_SCALE = gel_tau_mult * gel_tau_ref
_INV_PHI_SPAN = 1.0 / (gel_phi_ref - gel_phi)
_HALF_INV_ETA = 0.5 / eta


@njit(cache=True)
def pore_solid_fraction(m, S, phi_susp, v_dep):
    """Доля твердого парафина в поровом объеме нефти (1а): взвесь плюс осадок на стенках, [-]."""
    v_oil = m * (1.0 - S)
    v_sol = v_oil * phi_susp + v_dep
    return v_sol / (v_oil + v_dep) if v_oil + v_dep > 0.0 else 0.0


@njit(cache=True)
def yield_stress(phi_s):
    """Предел текучести геля по (1), [Па]. phi_s - объемная доля кристаллов в нефтяной фазе."""
    if phi_s <= gel_phi:
        return 0.0
    return _TAU_SCALE * ((phi_s - gel_phi) * _INV_PHI_SPAN) ** gel_n


@njit(cache=True)
def br_factor(xi):
    """Множитель Букингема-Райнера (2): доля пуазейлевского расхода бингамовской жидкости в трубе."""
    if xi >= 1.0:
        return 0.0
    return 1.0 - 4.0 / 3.0 * xi + xi ** 4 / 3.0


@njit(cache=True)
def gel_phi_eq(i, j, fi, grad_p, tau_y):
    """Равновесный множитель подвижности нефти по (3) для ячейки (i, j). Ровно 1 при tau_y = 0."""
    if tau_y <= 0.0:
        return 1.0
    num, den = 0.0, 0.0
    tau_coef = grad_p * _HALF_INV_ETA  # tau_w = r*|grad p|/(2*eta)
    for ij in range(Nr):
        wf = w4_cv[ij] * fi[i, j, ij]
        den += wf
        tau_w = r1[ij] * tau_coef
        if tau_w > tau_y:
            num += wf * br_factor(tau_y / tau_w)
    return num / den if den > 0.0 else 1.0
