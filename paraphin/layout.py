"""Раскладка массивов с именованными индексами: компоненты нефтяной фазы `Wc`, поля механизмов `kx`, строки скретча.

Индексы зависят только от флагов `constants.py` (числа групп парафина и включенных механизмов), поэтому
считаются здесь, а не в модулях, которые массивы заполняют: ядра, решатель, выгрузка и опыты берут их из одного места.
Как и флаги, это константы уровня модуля - numba вшивает их литералами.
"""
from paraphin.constants import wax_characterization, scn_bounds, wax_kinetics, asph_aggregation, Nx, Ny

# --- Компоненты нефтяной фазы Wc[Nx, Ny, NC] (`oil_composition`, `equations/Components.py`) -------------------------
N_W = 1 if wax_characterization == 'single' else len(scn_bounds) + 1  # число групп парафина (`lump_groups`)
IA_D = N_W      # растворенные асфальтены
IA_F = N_W + 1  # флокулы асфальтенов
I_R = N_W + 2   # смолы
NCB = N_W + 3   # «массовые» компоненты: по ним сходятся балансы массы, их сумма с остатком - единица
# Дальше - переносимые с нефтью величины, которые компонентами не являются (включаются флагами кинетики):
#   Wc[..., IS0 + k] - взвешенные кристаллы группы k, часть Wc[..., k] (`wax_kinetics`: взвесь не равновесная);
#   Wc[..., IN_F]    - число флокул асфальтенов на килограмм нефти (`asph_aggregation`), [1/кг].
IS0 = NCB
IN_F = IS0 + (N_W if wax_kinetics else 0)
NC = IN_F + (1 if asph_aggregation else 0)

# --- Поля механизмов kx[Nx, Ny, NKX] (`kinetics_params`, `equations/Deposition.py`) ----------------------------------
# Текущий слой - kx, новый - new_kx, обмен в `_swap_time_steps`. Один массив вместо отдельных полей: иначе каждое
# поле добавляло бы по два аргумента во все ядра шага.
KX_WEQ = 0             # [KX_WEQ, +N_W): равновесная взвесь групп на слое (`wax_kinetics`), [-]
KX_WSH = N_W           # [KX_WSH, +N_W): доли групп в стеночной кристаллизации этого шага, [-]
KX_GSH = 2 * N_W       # [KX_GSH, +N_W): доли групп в старении гель-отложения этого шага, [-]
KX_QW = 3 * N_W        # скорость потери порового объема на стеночную кристаллизацию, [1/с]
KX_QG = 3 * N_W + 1    # то же на старение гель-отложения, [1/с]
KX_QADA = 3 * N_W + 2  # то же на адсорбцию асфальтенов, [1/с]
KX_QADR = 3 * N_W + 3  # то же на адсорбцию смол, [1/с]
KX_GA = 3 * N_W + 4    # адсорбированные асфальтены, [кг/м^3 породы]
KX_GR = 3 * N_W + 5    # адсорбированные смолы, [кг/м^3 породы]
KX_VGEL = 3 * N_W + 6  # объем гель-отложения парафина в проводящих каналах, [м^3/м^3 породы]
KX_TS = 3 * N_W + 7    # температура породы (`thermal_nonequilibrium`), [C]
KX_GMAX = 3 * N_W + 8  # предельная адсорбция асфальтенов G_max = ads_gmax*a_v (для смачиваемости), [кг/м^3 породы]
KX_SIG0 = 3 * N_W + 9  # начальный объем удержанного (`ads_init_equilibrium`): от него считается повреждение, [-]
KX_UA = 3 * N_W + 10   # коэффициент сужения капилляров флокулами u_a = Ua*r^(1/3) (`asphaltenes`), [м^(2/3)/с]
KX_QPA = 3 * N_W + 11  # скорость потери порового объема на осадок асфальтены + смолы, [1/с]
NKX = 3 * N_W + 12

# --- Строки скретча rows[Nx, NROWS, Nr]: рабочие профили одной ячейки, свои на каждый i (иначе гонка в prange) -----
# Профили по радиусам ядер кольматации (ROW_U...ROW_TMP), прогоночные коэффициенты (ROW_A, ROW_B) и потоки нефти
# через четыре грани ячейки (ROW_FO, первые 4 элемента; `flows_in_cells` -> `components_equation`)
ROW_U, ROW_UW, ROW_UA, ROW_BW, ROW_BA, ROW_UE, ROW_TMP, ROW_A, ROW_B, ROW_FO = range(10)
NROWS = 10

# --- Векторы уравнения давления: неизвестная ячейки (i, j) - p_vec[P0 + i + j*PX] -----------------------------------
# С рамкой фиктивных ячеек, как уровни многосеточного решателя (`mg_solver.py`): матрица собирается прямо в его мелкий
# уровень, а векторы PCG - это строки его же буфера, без копий на каждом V-цикле. У рамки связи и решение нулевые.
PX = Nx + 2                  # шаг строки
P0 = PX + 1                  # индекс ячейки (0, 0)
NP = (Nx + 2) * (Ny + 2)     # длина векторов
