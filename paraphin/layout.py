"""Раскладка массивов с именованными индексами: компоненты нефтяной фазы `Wc`, поля механизмов `kx`, строки скретча.

Индексы зависят только от флагов `constants.py` (числа групп парафина и включенных механизмов), поэтому
считаются здесь, а не в модулях, которые массивы заполняют: ядра, решатель, выгрузка и опыты берут их из одного места.
Как и флаги, это константы уровня модуля - numba вшивает их литералами.
"""
import numpy as np

from paraphin.constants import (wax_characterization, scn_bounds, wax_kinetics, asph_aggregation, asphaltenes, Nx, Ny, Nr,
                                deposition_kinetics)

# --- Компоненты нефтяной фазы Wc[Nx, Ny, NC] (`oil_composition`, `equations/Components.py`) -------------------------
N_W = 1 if wax_characterization == 'single' else len(scn_bounds) + 1  # число групп парафина (`lump_groups`)
IA_D = N_W      # растворенные асфальтены
IA_F = N_W + 1  # флокулы асфальтенов
I_R = N_W + 2   # смолы
NCB = N_W + 3   # «массовые» компоненты: по ним сходятся балансы массы, их сумма с остатком - единица
# Дальше - переносимые с нефтью величины, которые компонентами не являются (включаются флагами кинетики):
#   Wc[..., IS0 + k] - взвешенные кристаллы группы k, часть Wc[..., k] (`wax_kinetics`: взвесь не равновесная);
#   Wc[..., IN_F]    - число флокул асфальтенов на килограмм нефти (`asph_aggregation`), [1/кг].
IS0 = NCB
IN_F = IS0 + (N_W if wax_kinetics else 0)
NC = IN_F + (1 if asph_aggregation else 0)
# Переносимые компоненты - первые NC_T. Без асфальтенов (и без взвеси `wax_kinetics` за ними) доли асфальтенов и смол
# ни на что не влияют, и переносятся только группы парафина: Wc[..., IA_D:] остаются начальными
NC_T = NC if (asphaltenes or wax_kinetics) else N_W
# Именованный вид Wc и Dep для Python-кода (выгрузка, опыты): `named(solver.Wc)['asph_f']` - вид на тот же буфер, без
# копии. В ядрах компоненты остаются индексами: перенос - один цикл по номеру компонента `for c in range(NC_T)`
WC = np.dtype([('wax', np.float64, (N_W,)), ('asph_d', np.float64), ('asph_f', np.float64), ('resin', np.float64)]
              + ([('sus', np.float64, (N_W,))] if wax_kinetics else []) + ([('nflocs', np.float64)] if asph_aggregation else []))


def named(a):
    """Вид массива [..., NC] (`Solver.Wc`, `Solver.Dep`, `bc_Wc`) с именованными полями dtype WC."""
    return a.view(WC)[..., 0]
# Один переносимый компонент без кинетики осаждения (однокомпонентная модель): облегченный перенос в
# `components_equation`, взвесь по группам Ws не пишется и не обменивается
LEAN = NC_T == 1 and not deposition_kinetics

# --- Поля механизмов kx[Nx, Ny], структурный dtype KX (`kinetics_params`, `equations/Deposition.py`) ------------------
# Текущий слой - kx, новый - new_kx, обмен в `_swap_time_steps`. Один массив вместо отдельных полей: иначе каждое
# поле добавляло бы по два аргумента во все ядра шага. В ядрах - `kx[i, j].qpa`, `kx[i, j].weq[k]` (к подмассивам -
# только поэлементно: векторные операции над ними дороги в компиляции, см. скважины `utils/well.py`), в Python -
# `kx['qpa']` (вид на поле). Обычный ndarray, не np.recarray: подкласс numba типизирует медленно.
KX = np.dtype([
    ('weq', np.float64, (N_W,)),  # равновесная взвесь групп на слое (`wax_kinetics`), [-]
    ('wsh', np.float64, (N_W,)),  # доли групп в стеночной кристаллизации этого шага, [-]
    ('gsh', np.float64, (N_W,)),  # доли групп в старении гель-отложения этого шага, [-]
    ('qw', np.float64),           # скорость потери порового объема на стеночную кристаллизацию, [1/с]
    ('qg', np.float64),           # то же на старение гель-отложения, [1/с]
    ('qada', np.float64),         # то же на адсорбцию асфальтенов, [1/с]
    ('qadr', np.float64),         # то же на адсорбцию смол, [1/с]
    ('ga', np.float64),           # адсорбированные асфальтены, [кг/м^3 породы]
    ('gr', np.float64),           # адсорбированные смолы, [кг/м^3 породы]
    ('vgel', np.float64),         # объем гель-отложения парафина в проводящих каналах, [м^3/м^3 породы]
    ('ts', np.float64),           # температура породы (`thermal_nonequilibrium`), [C]
    ('gmax', np.float64),         # предельная адсорбция асфальтенов G_max = ads_gmax*a_v (смачиваемость), [кг/м^3 породы]
    ('sig0', np.float64),         # начальный объем удержанного (`ads_init_equilibrium`): от него - повреждение, [-]
    ('ua', np.float64),           # коэффициент сужения капилляров флокулами u_a = Ua*r^(1/3) (`asphaltenes`), [м^(2/3)/с]
    ('qpa', np.float64),          # скорость потери порового объема на осадок асфальтены + смолы, [1/с]
])

# --- Строки скретча rows[Nx]: рабочие профили одной ячейки, свои на каждый i (иначе гонка в prange) ---------------
# Профили по радиусам ядер кольматации (u ... tmp) и прогоночные коэффициенты (a, b).
# Структурный dtype ROWS: строка кусочка - запись с подмассивами длины Nr, в ядрах `rows.u`, `rows.a` - обычные
# одномерные массивы-виды (передаются в функции без копий)
ROWS = np.dtype([(name, np.float64, (Nr,)) for name in ('u', 'uw', 'ua', 'bw', 'ba', 'ue', 'tmp', 'a', 'b')])

# --- Векторы уравнения давления: неизвестная ячейки (i, j) - p_vec[P0 + i + j*PX] -----------------------------------
# С рамкой фиктивных ячеек, как уровни многосеточного решателя (`mg_solver.py`): матрица собирается прямо в его мелкий
# уровень, а векторы PCG - это строки его же буфера, без копий на каждом V-цикле. У рамки связи и решение нулевые.
PX = Nx + 2                  # шаг строки
P0 = PX + 1                  # индекс ячейки (0, 0)
NP = (Nx + 2) * (Ny + 2)     # длина векторов
