def build(text: str) -> str:
    blocks = text.split('\n\n')

    # 1. Выбрасываем блоки, не входящие в журнальную версию
    kept = [b for b in blocks if not any(m in b for m in DROP_MARKERS)]
    # Абзацы, которые в журнальной версии заменены сжатыми (признак - начало абзаца)
    for prefix, short in SHORTER:
        hits = [n for n, b in enumerate(kept) if b.startswith(prefix)]
        if len(hits) != 1:
            print(f'  ВНИМАНИЕ: абзац для сжатия найден {len(hits)} раз: {prefix[:60]}')
        for n in hits:
            kept[n] = short

    # 2. Точечные правки текста
    out = '\n\n'.join(kept)
    for old, new in REPLACEMENTS:
        if old not in out:
            print(f'  ВНИМАНИЕ: не найдено для замены: {old[:60]}')
        out = out.replace(old, new)

    # 3. Подпись рис. 2 - своя (поле давления выброшено), рис. 4 - сжатая разность полей на месте полной
    out = re.sub(r'^Рис\. 2\..*$', lambda _m: CAPTIONS[2], out, count=1, flags=re.M)
    anchor = 'Занижение температуры влечет за собой завышение вязкости нефти.'
    out = out.replace(anchor, f'![](figures/fig8.png)\n\n{CAPTIONS[4]}\n\n{anchor}', 1)

    # 4. Ограничения - одним абзацем в конце раздела о моделях теплообмена
    tail = 'воспроизводит около 70% эффекта (0.0272 из 0.0385).'
    out = out.replace(tail, f'{tail}\n\n{LIMITATIONS}', 1)

    # 5. Страница подрисуночных подписей
    page = '# ПОДПИСИ К РИСУНКАМ\n\n'
    for stem, number in SHORT_FIGURES:
        # Подписи рис. 2 и 4 - свои, остальные берутся из текста как есть
        caption = CAPTIONS.get(number) or re.search(rf'^Рис\. {number}\..*$', out, flags=re.M).group(0)
        page += f'![](figures/{stem}.png)\n\n{caption}\n\n'
    cut = out.find('# ПОДПИСИ К РИСУНКАМ')
    if cut < 0:  # в полной версии страницы подписей нет — добавляем в конец
        cut = len(out)
    out = out[:cut].rstrip() + '\n\n' + page.rstrip() + '\n'
    return out


def main() -> None:
    sys.stdout.reconfigure(encoding='utf-8')
    src = (HERE / 'article.md').read_text(encoding='utf-8')
    result = build(src)
    (HERE / 'article_short.md').write_text(result, encoding='utf-8')

    figs = re.findall(r'figures/(\w+)\.png', result)
    body = result.split('# СПИСОК ЛИТЕРАТУРЫ')[0]
    order, seen = [], set()
    for n in (int(m) for m in re.findall(r'рис\. (\d)', body)):
        if n not in seen:
            seen.add(n)
            order.append(n)
    print(f'article_short.md записан: {len(result)} символов')
    print(f'  рисунков в тексте: {sorted(set(figs))}')
    print(f'  порядок ссылок: {order}, возрастает: {order == sorted(order)}')


if __name__ == '__main__':
    main()
