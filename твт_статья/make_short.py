"""Сборка журнальной версии статьи из полной.

Полная версия (`article.md`) содержит семь рисунков и 26 подрисунков; правила ТВТ разрешают
не более десяти подрисунков и семнадцати страниц. Журнальная версия получается из полной
механически, а не пишется отдельно: так числа и формулировки в обеих версиях не расходятся.

Что происходит:
  - рис. 1 заменяется на вариант без поля давления (6 подрисунков вместо 9);
  - выбрасываются карты кольматации, функция пор по размерам и наложенные изолинии;
  - поля разности заменяются сжатым вариантом на один момент времени (2 подрисунка);
  - раздел «Ограничения модели» сжимается в один абзац;
  - рисунки перенумеровываются, страница подписей пересобирается.

    python твт_статья/make_short.py

Результат: `твт_статья/article_short.md`. Сборка docx - отдельным вызовом pandoc.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Рисунки журнальной версии: файл -> номер в статье
SHORT_FIGURES = (('fig1s', 1), ('fig2', 2), ('fig8', 3), ('fig5', 4))

CAPTIONS = {
    1: ('Рис. 1. Поля температуры (а–в) и водонасыщенности (г–е) для варианта 1 на '
        'моменты времени t₁ = 195 сут (а, г), t₂ = 858 сут (б, д) и t₃ = 1522 сут (в, е). '
        'Треугольник — нагнетательная скважина, круг — добывающая. Числа на изолиниях — '
        'значения соответствующей величины; набор уровней единый для всех трех моментов '
        'времени.'),
    2: ('Рис. 2. Дебит добывающей скважины по нефти (черные линии, левая ось) и '
        'обводненность (серые линии, правая ось): 1 — теплообмен учитывается, '
        'wₚ = 0.20; 2 — теплообмен не учитывается, wₚ = 0.20; 3 — теплообмен не учитывается, '
        'wₚ = 0.'),
    3: ('Рис. 3. Разность полей температуры (а) и водонасыщенности (б) между вариантом 1 и '
        'вариантом 2 на момент t₂ = 858 сут, отвечающий максимальному расхождению. '
        'Положительные значения соответствуют более высоким температуре и водонасыщенности '
        'при учете теплообмена; штриховые изолинии — отрицательным значениям, жирная '
        'линия — нулевому.'),
    4: ('Рис. 4. Накопленная добыча нефти: 1 — теплообмен учитывается, wₚ = 0.20; 2 — '
        'теплообмен не учитывается, wₚ = 0.20; 3 — теплообмен не учитывается, wₚ = 0; '
        '4 — теплообмен по схеме Ловерье, wₚ = 0.20; 5 — теплообмен учитывается, wₚ = 0. '
        'Маркер отмечает момент достижения предельной обводненности.'),
}

# Блоки, целиком выпадающие из журнальной версии: (подстрока-признак, пояснение)
DROP_MARKERS = (
    'figures/fig3.png',            # карты кольматации
    'figures/fig6.png',            # функция пор по размерам
    'figures/fig4.png',            # наложенные изолинии
    'figures/fig7.png',            # полные карты разности
    'Рис. 3. Множители проницаемости',
    'Рис. 4. Функция распределения пор',
    'Рис. 5. Изолинии температуры',
    'Рис. 6. Разность полей температуры',
    'Механизм кольматации на уровне отдельных капилляров',
    'Наложение изолиний обоих вариантов',
    '## Ограничения модели',
    'Полученные оценки следует рассматривать с учетом принятых допущений.',
    'Вклад кристаллов парафина в вязкость нефтяной фазы описан соотношением',
    'Энергия активации вязкого течения нефти принята равной',
    'Вынос осевших частиц потоком (суффозия) не учитывался',
    'Зависимость вязкости от давления не учитывалась.',
)

# Точечные замены в тексте: панели рис. 1, ссылки на выброшенные рисунки, перенумерация
REPLACEMENTS = (
    ('(рис. 1а, 1г, 1ж)', '(рис. 1а–1в)'),
    ('(рис. 1б, 1д, 1з)', '(рис. 1г–1е)'),
    ('Поле давления (рис. 1в, 1е, 1и) сохраняет', 'Поле давления сохраняет'),
    ('Зона деградации фильтрационно-емкостных свойств (рис. 3) поэтому',
     'Зона деградации фильтрационно-емкостных свойств поэтому'),
    ('охватывает четверть площади элемента (рис. 3).', 'охватывает четверть площади элемента.'),
    ('Пространственное распределение вносимой погрешности дают поля разности (рис. 6), вычисленные '
     'на одни и те же моменты физического времени.',
     'Пространственное распределение вносимой погрешности дает поле разности (рис. 3), '
     'вычисленное на один и тот же момент физического времени.'),
    ('(рис. 2, 6а)', '(рис. 2)'),
    ('динамика накопленной добычи по всем вариантам — на рис. 7',
     'динамика накопленной добычи по всем вариантам — на рис. 4'),
    ('figures/fig1.png', 'figures/fig1s.png'),
)

# Сжатая замена раздела «Ограничения модели» - вставляется в конец раздела о моделях теплообмена
LIMITATIONS = (
    'Полученные оценки следует рассматривать с учетом принятых допущений. Вклад кристаллов '
    'парафина в вязкость нефтяной фазы описан соотношением Кригера—Догерти для разбавленной '
    'суспензии, дающим при $w_p = 0.20$ поправку не более 1.34, и не воспроизводит '
    'гелеобразование ниже температуры застывания; для нефтей с большим содержанием парафина '
    'и при более низкой температуре закачки эффект будет сильнее полученного. Энергия активации вязкого течения принята равной '
    '25 кДж/моль по типичному для парафинистых нефтей диапазону, и ее уточнение по замерам '
    'изменит количественные оценки, оставляя качественные выводы в силе. Вынос осевших частиц '
    'потоком и зависимость вязкости от давления не учитывались.'
)


def build(text: str) -> str:
    blocks = text.split('\n\n')

    # 1. Выбрасываем блоки, не входящие в журнальную версию
    kept = [b for b in blocks if not any(m in b for m in DROP_MARKERS)]

    # 2. Точечные правки текста
    out = '\n\n'.join(kept)
    for old, new in REPLACEMENTS:
        if old not in out:
            print(f'  ВНИМАНИЕ: не найдено для замены: {old[:60]}')
        out = out.replace(old, new)

    # 3. Подписи рис. 1 и 3 - свои, остальные перенумеровываются
    out = re.sub(r'^Рис\. 1\..*$', CAPTIONS[1], out, count=1, flags=re.M)
    out = re.sub(r'^Рис\. 7\..*$', CAPTIONS[4], out, count=1, flags=re.M)

    # Сжатый рисунок разности встает на место выброшенного полного
    anchor = 'Занижение температуры влечет за собой завышение вязкости нефти.'
    out = out.replace(anchor, f'![](figures/fig8.png)\n\n{CAPTIONS[3]}\n\n{anchor}', 1)

    # 4. Ограничения - одним абзацем в конце раздела о моделях теплообмена
    tail = 'сохраняется при любом из двух рассмотренных.'
    out = out.replace(tail, f'{tail}\n\n{LIMITATIONS}', 1)

    # 5. Страница подрисуночных подписей
    page = '# ПОДПИСИ К РИСУНКАМ\n\n'
    for stem, number in SHORT_FIGURES:
        page += f'![](figures/{stem}.png)\n\n{CAPTIONS[number]}\n\n'
    cut = out.find('# ПОДПИСИ К РИСУНКАМ')
    out = out[:cut] + page.rstrip() + '\n'
    return out


def main() -> None:
    sys.stdout.reconfigure(encoding='utf-8')
    src = (HERE / 'article.md').read_text(encoding='utf-8')
    result = build(src)
    (HERE / 'article_short.md').write_text(result, encoding='utf-8')

    figs = re.findall(r'figures/(\w+)\.png', result)
    body = result.split('# СПИСОК ЛИТЕРАТУРЫ')[0]
    order, seen = [], set()
    for n in (int(m) for m in re.findall(r'рис\. (\d)', body)):
        if n not in seen:
            seen.add(n)
            order.append(n)
    print(f'article_short.md записан: {len(result)} символов')
    print(f'  рисунков в тексте: {sorted(set(figs))}')
    print(f'  порядок ссылок: {order}, возрастает: {order == sorted(order)}')


if __name__ == '__main__':
    main()
